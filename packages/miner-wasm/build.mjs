#!/usr/bin/env node
// Compiles src/lbry_scan.c to WebAssembly (a scalar and a 4-way SIMD build) and
// embeds both (base64) into the core package so the app never needs a C
// toolchain at build time.
//
//   npm run build -w @lbcwallet/miner-wasm
//
// Requires clang with the wasm32 target and wasm-ld (LLVM >= 15).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src', 'lbry_scan.c');
const outDir = join(here, 'dist');
const generated = join(here, '..', 'core', 'src', 'mining', 'lbry-scan-wasm.generated.ts');
const clang = process.env.CLANG ?? 'clang';

mkdirSync(outDir, { recursive: true });

/** Compiles the scanner; `simd` selects the 4-way WebAssembly SIMD build. */
function compile(simd) {
  const wasmPath = join(outDir, simd ? 'lbry_scan_simd.wasm' : 'lbry_scan.wasm');
  execFileSync(
    clang,
    [
      '--target=wasm32',
      ...(simd ? ['-msimd128'] : []),
      '-O3',
      '-flto',
      '-nostdlib',
      '-fno-builtin',
      '-Wall',
      '-Werror',
      '-Wl,--no-entry',
      '-Wl,--lto-O3',
      '-Wl,-z,stack-size=65536',
      '-Wl,--initial-memory=262144',
      '-Wl,--max-memory=262144',
      '-o',
      wasmPath,
      src,
    ],
    { stdio: 'inherit' },
  );
  const wasm = readFileSync(wasmPath);
  const sha256 = createHash('sha256').update(wasm).digest('hex');
  console.log(`built ${wasmPath} (${wasm.length} bytes, sha256 ${sha256})`);
  return { wasm, sha256 };
}

const scalar = compile(false);
const simd = compile(true);
writeFileSync(
  generated,
  `// Generated by packages/miner-wasm/build.mjs from lbry_scan.c — do not edit.\n` +
    `// scalar: ${scalar.wasm.length} bytes, sha256 ${scalar.sha256}\n` +
    `// simd128: ${simd.wasm.length} bytes, sha256 ${simd.sha256}\n` +
    `export const LBRY_SCAN_WASM_SHA256 = '${scalar.sha256}';\n` +
    `export const LBRY_SCAN_WASM_BASE64 =\n  '${scalar.wasm.toString('base64')}';\n` +
    `export const LBRY_SCAN_SIMD_WASM_SHA256 = '${simd.sha256}';\n` +
    `export const LBRY_SCAN_SIMD_WASM_BASE64 =\n  '${simd.wasm.toString('base64')}';\n`,
);
