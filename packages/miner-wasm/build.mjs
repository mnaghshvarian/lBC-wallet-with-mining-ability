#!/usr/bin/env node
// Compiles src/lbry_scan.c to WebAssembly and embeds it (base64) into the core
// package so the app never needs a C toolchain at build time.
//
//   npm run build -w @lbcwallet/miner-wasm
//
// Requires clang with the wasm32 target and wasm-ld (LLVM >= 15).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src', 'lbry_scan.c');
const outDir = join(here, 'dist');
const wasmPath = join(outDir, 'lbry_scan.wasm');
const generated = join(here, '..', 'core', 'src', 'mining', 'lbry-scan-wasm.generated.ts');
const clang = process.env.CLANG ?? 'clang';

mkdirSync(outDir, { recursive: true });
execFileSync(
  clang,
  [
    '--target=wasm32',
    '-O3',
    '-flto',
    '-nostdlib',
    '-fno-builtin',
    '-Wall',
    '-Werror',
    '-Wl,--no-entry',
    '-Wl,--lto-O3',
    '-Wl,-z,stack-size=65536',
    '-Wl,--initial-memory=262144',
    '-Wl,--max-memory=262144',
    '-o',
    wasmPath,
    src,
  ],
  { stdio: 'inherit' },
);

const wasm = readFileSync(wasmPath);
const sha256 = createHash('sha256').update(wasm).digest('hex');
writeFileSync(
  generated,
  `// Generated by packages/miner-wasm/build.mjs from lbry_scan.c — do not edit.\n` +
    `// ${wasm.length} bytes, sha256 ${sha256}\n` +
    `export const LBRY_SCAN_WASM_SHA256 = '${sha256}';\n` +
    `export const LBRY_SCAN_WASM_BASE64 =\n  '${wasm.toString('base64')}';\n`,
);
console.log(`built ${wasmPath} (${wasm.length} bytes, sha256 ${sha256})`);
